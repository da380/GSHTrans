/**
 * @file Wigner.hpp
 * @brief The generalised Legendre functions, tabulated over colatitude.
 *
 * @details The value stored at upper index @f$N@f$, degree @f$l@f$ and order
 * @f$m@f$ is
 *
 * @f[ \sqrt{\frac{2l+1}{4\pi}}\, d^l_{Nm}(\theta), @f]
 *
 * where @f$d^l_{Nm} = P^N_{lm}(\cos\theta)@f$ is the generalised Legendre
 * function of Dahlen & Tromp (1998) eq. (C.115) — **upper index first**.
 * Orthonormalisation is the only normalisation offered.
 *
 * Values come from a two-term recursion up the degrees at fixed
 * @f$(N, \theta)@f$, seeded at @f$l = |N|@f$ and closed at each degree by the
 * two boundary orders @f$m = \pm l@f$. Nothing forms a factorial: the seed row
 * is generated by the binomial step @f$C(2l, k) = C(2l, k-1)(2l-k+1)/k@f$ and
 * the boundary values ride up the degree loop by their own one-term
 * recursion, which is both cheaper and more accurate than the closed form —
 * that exponentiates a logarithm of size @f$O(l\log 4)@f$ and loses bits in
 * proportion, where each recursion step multiplies by a factor of order one.
 *
 * The table is large: about 648 MB at @f$l_{\max} = 256@f$ with
 * @f$n_{\max} = 2@f$ over all upper indices, against 2.1 MB for a complex
 * field on the same grid. A grid may therefore decline to hold one and
 * generate each block as it is needed, which is what ComputeBlock is separable
 * for.
 *
 * @see WignerMatrices.hpp, which holds the same values in the layout a matrix
 * product wants, and is checked against this one.
 * @see docs/gshtrans-reference.tex, "Conventions", for the conventions.
 */

